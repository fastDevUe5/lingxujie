ALXJCharacter::ALXJCharacter()
{
	PrimaryActorTick.bCanEverTick = true;

	GetCapsuleComponent()->InitCapsuleSize(42.f, 90.f);

	bUseControllerRotationPitch = false;
	bUseControllerRotationYaw = false;
	bUseControllerRotationRoll = false;

	UCharacterMovementComponent* Move = GetCharacterMovement();
	Move->bOrientRotationToMovement = true;
	Move->RotationRate = FRotator(0.f, 900.f, 0.f);
	Move->JumpZVelocity = 720.f;
	Move->GravityScale = 1.35f;
	Move->AirControl = 0.7f;
	Move->MaxWalkSpeed = WalkSpeed;
	Move->BrakingDecelerationWalking = 2200.f;
	Move->GroundFriction = 8.f;
	Move->MaxStepHeight = 72.f;

	CameraBoom = CreateDefaultSubobject<USpringArmComponent>(TEXT("CameraBoom"));
	CameraBoom->SetupAttachment(GetCapsuleComponent());
	CameraBoom->SetRelativeLocation(FVector(0.f, 0.f, 80.f));
	CameraBoom->TargetArmLength = 480.f;
	CameraBoom->SocketOffset = FVector(0.f, 60.f, 10.f);
	CameraBoom->bUsePawnControlRotation = false;
	CameraBoom->bDoCollisionTest = true;
	CameraBoom->ProbeSize = 14.f;
	CameraBoom->bEnableCameraLag = true;
	CameraBoom->CameraLagSpeed = 10.f;
	CameraBoom->bEnableCameraRotationLag = true;
	CameraBoom->CameraRotationLagSpeed = 14.f;
	CameraBoom->SetUsingAbsoluteRotation(true);
	CameraBoom->SetWorldRotation(FRotator(CameraPitch, CameraYaw, 0.f));

	FollowCamera = CreateDefaultSubobject<UCameraComponent>(TEXT("FollowCamera"));
	FollowCamera->SetupAttachment(CameraBoom, USpringArmComponent::SocketName);
	FollowCamera->bUsePawnControlRotation = false;
	FollowCamera->SetFieldOfView(DefaultFieldOfView);

	Combat = CreateDefaultSubobject<ULXJCombatComponent>(TEXT("Combat"));
	Health = CreateDefaultSubobject<ULXJHealthComponent>(TEXT("Health"));
	Health->MaxHealth = 300.f;
	Progress = CreateDefaultSubobject<ULXJProgressComponent>(TEXT("Progress"));
	Progress->SetStatTargets(Health, Combat);
	Inventory = CreateDefaultSubobject<ULXJInventoryComponent>(TEXT("Inventory"));
	Inventory->SetStatTargets(Health, Combat);

	// Robe: a slightly tapered cylinder; head: sphere; sword: thin cube on the back.
	BodyMesh = CreateDefaultSubobject<UStaticMeshComponent>(TEXT("BodyMesh"));
	BodyMesh->SetupAttachment(GetCapsuleComponent());
	BodyMesh->SetCollisionEnabled(ECollisionEnabled::NoCollision);
	BodyMesh->SetCanEverAffectNavigation(false);
	BodyMesh->SetRelativeLocation(FVector(0.f, 0.f, -26.f));
	BodyMesh->SetRelativeScale3D(FVector(0.46f, 0.46f, 1.05f));

	HeadMesh = CreateDefaultSubobject<UStaticMeshComponent>(TEXT("HeadMesh"));
	HeadMesh->SetupAttachment(GetCapsuleComponent());
	HeadMesh->SetCollisionEnabled(ECollisionEnabled::NoCollision);
	HeadMesh->SetCanEverAffectNavigation(false);
	HeadMesh->SetRelativeLocation(FVector(0.f, 0.f, 62.f));
	HeadMesh->SetRelativeScale3D(FVector(0.40f, 0.40f, 0.40f));

	SwordMesh = CreateDefaultSubobject<UStaticMeshComponent>(TEXT("SwordMesh"));
	SwordMesh->SetupAttachment(GetCapsuleComponent());
	SwordMesh->SetCollisionEnabled(ECollisionEnabled::NoCollision);
	SwordMesh->SetCanEverAffectNavigation(false);
	SwordMesh->SetRelativeLocation(FVector(-16.f, 18.f, 10.f));
	SwordMesh->SetRelativeRotation(FRotator(18.f, 0.f, 22.f));
	SwordMesh->SetRelativeScale3D(FVector(0.06f, 0.06f, 0.85f));

	static ConstructorHelpers::FObjectFinder<UStaticMesh> CylinderMesh(TEXT("/Engine/BasicShapes/Cylinder.Cylinder"));
	static ConstructorHelpers::FObjectFinder<UStaticMesh> SphereMesh(TEXT("/Engine/BasicShapes/Sphere.Sphere"));
	static ConstructorHelpers::FObjectFinder<UStaticMesh> CubeMesh(TEXT("/Engine/BasicShapes/Cube.Cube"));

	if (CylinderMesh.Succeeded())
	{
		BodyMesh->SetStaticMesh(CylinderMesh.Object);
	}
	if (SphereMesh.Succeeded())
	{
		HeadMesh->SetStaticMesh(SphereMesh.Object);
	}
	if (CubeMesh.Succeeded())
	{
		SwordMesh->SetStaticMesh(CubeMesh.Object);
	}
}

void ALXJCharacter::BeginPlay()
{
	Super::BeginPlay();

	// Materials are generated by Tools/build_level.py; fail soft so the game still runs.
	if (UMaterialInterface* RobeMaterial = LoadObject<UMaterialInterface>(nullptr, TEXT("/Game/Materials/M_Jade.M_Jade")))
	{
		BodyMesh->SetMaterial(0, RobeMaterial);
	}
	if (UMaterialInterface* HeadMaterial = LoadObject<UMaterialInterface>(nullptr, TEXT("/Game/Materials/M_Stone.M_Stone")))
	{
		HeadMesh->SetMaterial(0, HeadMaterial);
	}
	if (UMaterialInterface* SwordMaterial = LoadObject<UMaterialInterface>(nullptr, TEXT("/Game/Materials/M_Qi.M_Qi")))
	{
		SwordMesh->SetMaterial(0, SwordMaterial);
	}

	GetCharacterMovement()->MaxWalkSpeed = WalkSpeed;
	FollowCamera->SetFieldOfView(DefaultFieldOfView);

	// Start the camera where the PlayerStart points instead of always facing world +X.
	if (AController* OwningController = GetController())
	{
		CameraYaw = OwningController->GetControlRotation().Yaw;
	}
	CameraBoom->SetWorldRotation(FRotator(CameraPitch, CameraYaw, 0.f));

	SpawnLocation = GetActorLocation();
	Health->OnDeath.AddUObject(this, &ALXJCharacter::HandleDeath);
	UE_LOG(LogTemp, Log, TEXT("[LingXuJie] Player ready at %s (level %d)"), *SpawnLocation.ToCompactString(), Progress->GetLevel());
}

void ALXJCharacter::HandleDeath(AActor* DeadActor, AActor* Killer)
{
	UE_LOG(LogTemp, Log, TEXT("[LingXuJie] Player died, respawning at %s"), *SpawnLocation.ToCompactString());
	Health->ResetHealth();
	SetActorLocation(SpawnLocation);
	GetCharacterMovement()->StopMovementImmediately();
}

void ALXJCharacter::Tick(float DeltaSeconds)
{
	Super::Tick(DeltaSeconds);

	UpdateLandShake(DeltaSeconds);
	ReadDebugShortcuts();
	UpdateLook(DeltaSeconds);
	UpdateJumpAndGlide(DeltaSeconds);
	UpdateDash(DeltaSeconds);
	UpdateMove(DeltaSeconds);
	UpdateCombatInput();
}

void ALXJCharacter::UpdateCombatInput()
{
	APlayerController* PC = Cast<APlayerController>(GetController());
	if (!PC || !Combat || !Health || Health->IsDead())
	{
		return;
	}

	const FKey Slots[3] = { EKeys::LeftMouseButton, EKeys::One, EKeys::Two };
	for (int32 Index = 0; Index < 3; ++Index)
	{
		const bool bDown = PC->IsInputKeyDown(Slots[Index]) || (Index == 0 && PC->IsInputKeyDown(EKeys::J));
		if (bDown && !bSkillKeysHeld[Index])
		{
			bSkillKeysHeld[Index] = true;

			// Face where the camera looks before swinging: standing still otherwise leaves
			// the actor facing its last movement direction and every sweep misses.
			SetActorRotation(FRotator(0.f, CameraYaw, 0.f));
			if (Combat->TryUse(Index))
			{
				UE_LOG(LogTemp, Verbose, TEXT("[LingXuJie] Used slot %d facing %.0f"), Index, CameraYaw);
			}
		}
		else if (!bDown)
		{
			bSkillKeysHeld[Index] = false;
		}
	}
}

void ALXJCharacter::Landed(const FHitResult& Hit)
{
	Super::Landed(Hit);

	LandShakeTime = LandShakeDuration;
	bGliding = false;
	GetCharacterMovement()->GravityScale = 1.35f;
}

void ALXJCharacter::UpdateLandShake(float DeltaSeconds)
{
	if (LandShakeTime <= 0.f)
	{
		return;
	}

	LandShakeTime = FMath::Max(0.f, LandShakeTime - DeltaSeconds);
	const float Alpha = LandShakeTime / FMath::Max(LandShakeDuration, KINDA_SMALL_NUMBER);
	const float Offset = FMath::Sin(LandShakeTime * 62.f) * 3.f * Alpha * Alpha;

	FollowCamera->SetRelativeLocation(FVector(0.f, 0.f, -FMath::Abs(Offset)));
	FollowCamera->SetRelativeRotation(FRotator(Offset * 0.35f, 0.f, 0.f));

	if (LandShakeTime <= 0.f)
	{
		FollowCamera->SetRelativeLocation(FVector::ZeroVector);
		FollowCamera->SetRelativeRotation(FRotator::ZeroRotator);
	}
}

void ALXJCharacter::UpdateLook(float DeltaSeconds)
{
	APlayerController* PC = Cast<APlayerController>(GetController());
	if (!PC)
	{
		return;
	}

	if (PC->PlayerInput)
	{
		float MouseDX = 0.f;
		float MouseDY = 0.f;
		PC->GetInputMouseDelta(MouseDX, MouseDY);
		CameraYaw += MouseDX * MouseSensitivity;
		CameraPitch = FMath::Clamp(CameraPitch - MouseDY * MouseSensitivity, -70.f, 25.f);
	}

	const bool bLookLeft = PC->IsInputKeyDown(EKeys::Q);
	const bool bLookRight = PC->IsInputKeyDown(EKeys::E);
	if (bLookLeft != bLookRight)
	{
		CameraYaw += (bLookRight ? 1.f : -1.f) * CameraYawRate * DeltaSeconds;
	}

	CameraBoom->SetWorldRotation(FRotator(CameraPitch, CameraYaw, 0.f));
	if (Combat)
	{
		// Attacks follow the camera, not the (possibly stale) actor facing.
		Combat->SetAimDirection(FRotator(0.f, CameraYaw, 0.f).Vector());
	}
	const float TargetFOV = bSprinting ? SprintFieldOfView : DefaultFieldOfView;
	FollowCamera->SetFieldOfView(FMath::FInterpTo(FollowCamera->FieldOfView, TargetFOV, DeltaSeconds, 6.f));
}

void ALXJCharacter::UpdateMove(float DeltaSeconds)
{
	APlayerController* PC = Cast<APlayerController>(GetController());
	if (!PC)
	{
		return;
	}

	const float ForwardAxis = (PC->IsInputKeyDown(EKeys::W) || PC->IsInputKeyDown(EKeys::Up) ? 1.f : 0.f)
		- (PC->IsInputKeyDown(EKeys::S) || PC->IsInputKeyDown(EKeys::Down) ? 1.f : 0.f);
	const float RightAxis = (PC->IsInputKeyDown(EKeys::D) || PC->IsInputKeyDown(EKeys::Right) ? 1.f : 0.f)
		- (PC->IsInputKeyDown(EKeys::A) || PC->IsInputKeyDown(EKeys::Left) ? 1.f : 0.f);

	bSprinting = (PC->IsInputKeyDown(EKeys::LeftShift) || PC->IsInputKeyDown(EKeys::RightShift))
		&& (ForwardAxis != 0.f || RightAxis != 0.f);

	const bool bDashing = DashTimeLeft > 0.f;
	GetCharacterMovement()->MaxWalkSpeed = bDashing ? DashSpeed : (bSprinting ? SprintSpeed : WalkSpeed);

	if (ForwardAxis == 0.f && RightAxis == 0.f)
	{
		return;
	}

	const FRotator FlatYaw(0.f, CameraYaw, 0.f);
	AddMovementInput(FlatYaw.Vector(), ForwardAxis);
	AddMovementInput(FRotator(0.f, CameraYaw + 90.f, 0.f).Vector(), RightAxis);
}

void ALXJCharacter::UpdateJumpAndGlide(float DeltaSeconds)
{
	APlayerController* PC = Cast<APlayerController>(GetController());
	if (!PC)
	{
		return;
	}

	const bool bJumpDown = PC->IsInputKeyDown(EKeys::SpaceBar);
	if (bJumpDown && !bJumpKeyHeld)
	{
		Jump();
	}
	bJumpKeyHeld = bJumpDown;

	// Glide (a minimal "flying sword" stand-in): hold jump while falling.
	UCharacterMovementComponent* Move = GetCharacterMovement();
	const bool bFalling = Move->IsFalling();
	const bool bShouldGlide = bFalling && bJumpDown && Move->Velocity.Z < -50.f;

	if (bShouldGlide && !bGliding)
	{
		bGliding = true;
		Move->GravityScale = GlideGravityScale;
		UE_LOG(LogTemp, Log, TEXT("[LingXuJie] Glide start"));
	}
	else if (!bShouldGlide && bGliding)
	{
		bGliding = false;
		Move->GravityScale = 1.35f;
	}

	if (bGliding)
	{
		// Cap the fall and push forward: reads as a slow sword glide rather than a drop.
		if (Move->Velocity.Z < -GlideFallSpeedCap)
		{
			Move->Velocity.Z = -GlideFallSpeedCap;
		}
		AddMovementInput(GetActorForwardVector(), GlideForwardPush * DeltaSeconds / FMath::Max(WalkSpeed, 1.f));
	}
}

void ALXJCharacter::UpdateDash(float DeltaSeconds)
{
	APlayerController* PC = Cast<APlayerController>(GetController());
	if (!PC)
	{
		return;
	}

	DashCooldownLeft = FMath::Max(0.f, DashCooldownLeft - DeltaSeconds);
	DashTimeLeft = FMath::Max(0.f, DashTimeLeft - DeltaSeconds);

	const bool bDashDown = PC->IsInputKeyDown(EKeys::LeftControl) || PC->IsInputKeyDown(EKeys::C);
	if (bDashDown && !bDashKeyHeld && DashCooldownLeft <= 0.f)
	{
		const FRotator FlatYaw(0.f, CameraYaw, 0.f);
		const FVector Direction = bGliding ? GetActorForwardVector() : FlatYaw.Vector();
		LaunchCharacter(Direction * DashSpeed, true, false);
		DashTimeLeft = DashDuration;
		DashCooldownLeft = DashCooldown;
		bDashKeyHeld = true;
		UE_LOG(LogTemp, Log, TEXT("[LingXuJie] Dash"));
		return;
	}

	if (!bDashDown)
	{
		bDashKeyHeld = false;
	}
}

void ALXJCharacter::ReadDebugShortcuts()
{
	APlayerController* PC = Cast<APlayerController>(GetController());
	if (!PC)
	{
		return;
	}

	// Escape quits while there is no menu yet (P0 sandbox convenience).
	if (PC->IsInputKeyDown(EKeys::Escape))
	{
		PC->ConsoleCommand(TEXT("quit"));
	}
}
